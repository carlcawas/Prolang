let temperature = 35;
let weather = temperature > 30 ? "Hot" : "Cool";

// Nested ternary
let grade = 88;
let letterGrade = grade >= 90 ? "A"
               : grade >= 80 ? "B"
               : grade >= 70 ? "C"
               : "F";

console.log(weather);     // "Hot"
console.log(letterGrade); // "B"